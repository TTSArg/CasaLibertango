CREATE TABLE properties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL UNIQUE,
    name VARCHAR(180) NOT NULL,
    address VARCHAR(300) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE guests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(180) NOT NULL,
    email VARCHAR(254) NOT NULL,
    preferred_locale VARCHAR(5) NOT NULL DEFAULT 'es',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id BIGINT NOT NULL REFERENCES properties(id),
    guest_id BIGINT NOT NULL REFERENCES guests(id),
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'inquiry',
    guest_count SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT reservation_dates_valid CHECK (check_out > check_in),
    CONSTRAINT reservation_guest_count_valid CHECK (guest_count > 0),
    CONSTRAINT reservation_status_valid CHECK (status IN ('inquiry', 'pending', 'confirmed', 'cancelled', 'completed'))
);

CREATE INDEX reservations_property_dates_idx ON reservations(property_id, check_in, check_out);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    provider VARCHAR(60) NOT NULL,
    external_reference VARCHAR(180),
    amount NUMERIC(12, 2) NOT NULL,
    currency CHAR(3) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT payment_amount_nonnegative CHECK (amount >= 0),
    CONSTRAINT payment_status_valid CHECK (status IN ('pending', 'authorized', 'paid', 'failed', 'refunded'))
);
